/** 按名称/城市/标签模糊搜索 */
export function searchSchools(keyword) {
  const kw = (keyword || '').trim().toLowerCase()
  if (!kw) return schools
  return schools.filter(
    (s) =>
      s.name.toLowerCase().includes(kw) ||
      s.city.toLowerCase().includes(kw) ||
      s.type.toLowerCase().includes(kw) ||
      s.region.toLowerCase().includes(kw) ||
      s.tags.some((t) => t.toLowerCase().includes(kw))
  )
}

/** 获取指定院校 */
export function getSchool(id) {
  return schools.find((s) => s.id === id)
}

/** 同地区院校推荐 */
export function peerSchools(school, count = 3) {
  return schools
    .filter((s) => s.region === school.region && s.id !== school.id)
    .slice(0, count)
}
