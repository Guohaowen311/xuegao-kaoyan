function toSchool(raw) {
  const [id, name, city, region, type, tagsStr, intro] = raw
  // 第四轮学科评估完整数据（教育部学位中心官方公开结果）
  const counts = evalMapping[id]
  const evalKnown = Array.isArray(counts)
  return {
    id,
    name,
    city,
    region,
    type,
    tags: tagsStr ? tagsStr.split('|') : [],
    intro,
    evalA: {
      ap: evalKnown ? counts[0] : 0,
      a: evalKnown ? counts[1] : 0,
      am: evalKnown ? counts[2] : 0,
      bp: evalKnown ? counts[3] : 0,
      b: evalKnown ? counts[4] : 0,
      bm: evalKnown ? counts[5] : 0,
      cp: evalKnown ? counts[6] : 0,
      c: evalKnown ? counts[7] : 0,
      cm: evalKnown ? counts[8] : 0
    },
    evalKnown,
    // 复试线示例数据仅收录部分重点院校
    retest: RETEST[id] || []
  }
}

