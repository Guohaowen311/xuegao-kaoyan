/** 根据当前日期计算阶段状态：done / active / upcoming */
export function stageStatus(stage) {
  const now = new Date()
  const start = new Date(stage.start + 'T00:00:00')
  const end = new Date(stage.end + 'T23:59:59')
  if (now < start) return 'upcoming'
  if (now > end) return 'done'
  return 'active'
}

